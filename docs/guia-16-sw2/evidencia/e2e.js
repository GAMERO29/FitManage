const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 820 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  const errores = [];
  p.on('console', m => { if (m.type() === 'error') errores.push(m.text()); });
  p.on('pageerror', e => errores.push(String(e)));
  const S = async (n) => { await p.waitForTimeout(350); return p.screenshot({ path: `./${n}.png`, fullPage: true }); };
  await p.goto('http://localhost:8765/');
  await S('01-ingreso');
  await p.fill('input[name=correo]', 'admin@demo.local');
  await p.fill('input[name=contrasena]', 'clave-equivocada');
  await p.click('#form-ingreso button[type=submit]');
  await p.waitForSelector('#form-ingreso [data-error]:not(:empty)');
  console.log('login malo:', await p.textContent('#form-ingreso [data-error]'));
  await p.fill('input[name=contrasena]', 'clave-de-demo-local');
  await p.click('#form-ingreso button[type=submit]');
  await p.waitForSelector('#pantalla-recepcion:not([hidden])');
  await p.fill('input[name=numero]', '1090123456');
  await p.press('input[name=numero]', 'Enter');
  await p.waitForSelector('.estado');
  await S('02-no-registrado');
  console.log('404:', await p.textContent('.estado-veredicto'));
  await p.click('.estado >> text=Registrar socio');
  await p.fill('input[name=nombres]', 'Ana María');
  await p.fill('input[name=apellidos]', 'Prueba Demo');
  await p.fill('input[name=telefono]', '3001234567');
  await p.check('input[name=autoriza]');
  await S('03-registro-socio');
  await p.click('#form-socio button[type=submit]');
  await p.waitForSelector('.estado[data-estado=SIN_MEMBRESIA]');
  console.log('tras registro:', await p.textContent('.estado'));
  await p.click('.estado >> text=Registrar pago');
  const mensual = await p.$$eval('select[name=planId] option', os => os.find(o => o.textContent.startsWith('Mensual')).value);
  await p.selectOption('select[name=planId]', mensual);
  await p.selectOption('select[name=medio]', 'NEQUI');
  await p.fill('input[name=referencia]', 'M123456');
  await S('04-pago');
  // doble clic: dos envíos con la misma clave
  await p.$eval('#form-pago', f => { f.requestSubmit(); f.requestSubmit(); });
  await p.waitForSelector('.estado[data-estado=ACTIVO]');
  await p.waitForTimeout(400);
  await S('05-activo');
  console.log('activo:', await p.textContent('#resultado'));
  // celular
  const m = await b.newContext({ ...require('playwright').devices['Pixel 7'] });
  const q = await m.newPage();
  await q.goto('http://localhost:8765/');
  await q.fill('input[name=correo]', 'admin@demo.local');
  await q.fill('input[name=contrasena]', 'clave-de-demo-local');
  await q.click('#form-ingreso button[type=submit]');
  await q.waitForSelector('#pantalla-recepcion:not([hidden])');
  await q.fill('input[name=numero]', '1090123456');
  await q.press('input[name=numero]', 'Enter');
  await q.waitForSelector('.estado[data-estado=ACTIVO]');
  await q.waitForTimeout(350); await q.screenshot({ path: './06-celular.png', fullPage: true });
  // oscuro
  const o = await b.newContext({ viewport: { width: 900, height: 700 }, colorScheme: 'dark' });
  const r = await o.newPage(); await r.goto('http://localhost:8765/'); await r.screenshot({ path: './07-oscuro.png' });
  console.log('errores consola:', JSON.stringify(errores));
  await b.close();
})();
